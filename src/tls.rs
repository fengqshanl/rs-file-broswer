use std::{
    net::IpAddr,
    path::{Path, PathBuf},
    time::{SystemTime, UNIX_EPOCH},
};

use anyhow::{Context, Result};
use base64::{engine::general_purpose::STANDARD, Engine as _};
use rcgen::{Certificate, CertificateParams, DnType, SanType};
use serde::{Deserialize, Serialize};
use time::{Duration as TimeDuration, OffsetDateTime};

use crate::{config::Config, error::log};

/// Self-signed certificates are valid for one year and are re-issued during
/// the last 30 days, so a long-running installation never hits a hard-coded
/// expiration date.
const CERT_VALID_DAYS: i64 = 365;
const CERT_RENEW_WINDOW_SECS: i64 = 30 * 24 * 3600;
const META_FILE: &str = "self-signed.json";
/// CommonName written into certificates generated by this project. Used to
/// distinguish them from certificates supplied by the operator.
const SELF_SIGNED_MARKER: &[u8] = b"AgentGod Files";

#[derive(Serialize, Deserialize)]
struct CertMeta {
    /// Expiry as a Unix timestamp, seconds.
    not_after: i64,
}

/// Reuses a valid certificate if present; otherwise creates a self-signed one
/// whose SANs cover loopback plus every configured extra IP/DNS.
///
/// Certificates placed in `TLS_DIR` by the operator (trusted certs) are never
/// overwritten. Only certificates that we generated ourselves carry metadata,
/// and only those are rotated before expiry.
pub fn ensure_self_signed(cfg: &Config) -> Result<(PathBuf, PathBuf)> {
    std::fs::create_dir_all(&cfg.tls_dir)
        .with_context(|| format!("无法创建 TLS 目录: {}", cfg.tls_dir.display()))?;

    let cert_path = cfg.tls_dir.join("cert.pem");
    let key_path = cfg.tls_dir.join("key.pem");
    let meta_path = cfg.tls_dir.join(META_FILE);

    if cert_path.exists() && key_path.exists() {
        match read_meta(&meta_path) {
            Some(meta) if !renewal_due(meta.not_after) => {
                return Ok((cert_path, key_path));
            }
            Some(_) => log("自签名 TLS 证书即将到期，正在重新签发"),
            None if !cert_is_self_generated(&cert_path) => {
                // No metadata and not ours: treat as an operator-supplied
                // trusted certificate and leave it alone.
                return Ok((cert_path, key_path));
            }
            None => log("检测到旧版本生成的自签名证书，正在重新签发"),
        }
    }

    let mut dns_names = vec!["localhost".to_string()];
    for name in &cfg.tls_extra_dns {
        if !dns_names.iter().any(|existing| existing == name) {
            dns_names.push(name.clone());
        }
    }

    let now = OffsetDateTime::now_utc();
    let not_after = now + TimeDuration::days(CERT_VALID_DAYS);
    let mut params = CertificateParams::new(dns_names);
    // A day of slack tolerates a client whose clock is slightly behind.
    params.not_before = now - TimeDuration::days(1);
    params.not_after = not_after;
    params
        .distinguished_name
        .push(DnType::CommonName, "AgentGod Files");
    params
        .distinguished_name
        .push(DnType::OrganizationName, "AgentGod");

    let mut ips: Vec<IpAddr> = vec![
        IpAddr::from([127, 0, 0, 1]),
        IpAddr::from([0u16, 0, 0, 0, 0, 0, 0, 1]),
    ];
    ips.extend(cfg.tls_extra_ips.iter().copied());
    let mut seen_ips = std::collections::HashSet::new();
    for ip in ips {
        if seen_ips.insert(ip) {
            params.subject_alt_names.push(SanType::IpAddress(ip));
        }
    }

    let certificate = Certificate::from_params(params).context("生成自签名 TLS 证书失败")?;

    std::fs::write(
        &cert_path,
        certificate.serialize_pem().context("编码 TLS 证书失败")?,
    )
    .context("写入 TLS 证书失败")?;
    std::fs::write(&key_path, certificate.serialize_private_key_pem())
        .context("写入 TLS 私钥失败")?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&key_path, std::fs::Permissions::from_mode(0o600))
            .context("设置 TLS 私钥权限失败")?;
    }

    let meta = CertMeta {
        not_after: not_after.unix_timestamp(),
    };
    std::fs::write(
        &meta_path,
        serde_json::to_vec(&meta).context("编码 TLS 元数据失败")?,
    )
    .context("写入 TLS 元数据失败")?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&meta_path, std::fs::Permissions::from_mode(0o600))
            .context("设置 TLS 元数据权限失败")?;
    }

    Ok((cert_path, key_path))
}

fn read_meta(path: &Path) -> Option<CertMeta> {
    let bytes = std::fs::read(path).ok()?;
    serde_json::from_slice(&bytes).ok()
}

fn unix_now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_secs() as i64)
        .unwrap_or(0)
}

fn renewal_due(not_after: i64) -> bool {
    not_after.saturating_sub(unix_now()) <= CERT_RENEW_WINDOW_SECS
}

/// X.509 encodes the CommonName as plain ASCII inside the DER body. Looking
/// for our own CN is enough to tell a generated certificate from an imported
/// one without pulling in a full X.509 parser.
fn cert_is_self_generated(path: &Path) -> bool {
    let Ok(pem) = std::fs::read_to_string(path) else {
        return false;
    };
    let body: String = pem
        .lines()
        .filter(|line| !line.starts_with("-----"))
        .collect();
    let Ok(der) = STANDARD.decode(body.as_bytes()) else {
        return false;
    };
    der.windows(SELF_SIGNED_MARKER.len())
        .any(|window| window == SELF_SIGNED_MARKER)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renewal_only_triggers_close_to_expiry() {
        let now = unix_now();
        assert!(!renewal_due(now + 365 * 24 * 3600));
        assert!(!renewal_due(now + CERT_RENEW_WINDOW_SECS + 1));
        assert!(renewal_due(now + CERT_RENEW_WINDOW_SECS - 1));
        assert!(renewal_due(now - 1));
    }

    #[test]
    fn only_our_own_certificates_are_eligible_for_rotation() {
        let dir = tempfile::tempdir().expect("temp dir");
        let path = dir.path().join("cert.pem");
        let pem = |der: &[u8]| {
            format!(
                "-----BEGIN CERTIFICATE-----\n{}\n-----END CERTIFICATE-----\n",
                STANDARD.encode(der)
            )
        };
        std::fs::write(&path, pem(b"xxAgentGod Filesyy")).expect("write cert");
        assert!(cert_is_self_generated(&path));
        std::fs::write(&path, pem(b"xxSome Other CAyy")).expect("write cert");
        assert!(!cert_is_self_generated(&path));
        std::fs::write(&path, "not a certificate").expect("write cert");
        assert!(!cert_is_self_generated(&path));
    }
}
